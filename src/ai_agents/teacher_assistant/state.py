"""Task contracts and shared teacher assistant graph state."""

from typing import Annotated, Literal, TypedDict
from uuid import uuid4

from langchain_core.messages import AnyMessage
from langgraph.graph.message import add_messages
from pydantic import BaseModel, ConfigDict, Field, JsonValue, model_validator

from .workflow_config import TaskStatus


class Contract(BaseModel):
    model_config = ConfigDict(extra="forbid")


class Task(Contract):
    task_id: str = Field(default_factory=lambda: str(uuid4()))
    task_type: str = Field(min_length=1)
    title: str = Field(min_length=1)
    plan_id: str | None = Field(default=None, min_length=1)
    sequence_number: int | None = Field(default=None, ge=1)
    status: TaskStatus = TaskStatus.QUEUED

    inputs: dict[str, JsonValue] = Field(default_factory=dict)
    result: JsonValue = None
    guidance: list[str] = Field(default_factory=list)

    mild_issues: list[dict[str, JsonValue]] = Field(default_factory=list)
    moderate_issues: list[dict[str, JsonValue]] = Field(default_factory=list)
    severe_issues: list[dict[str, JsonValue]] = Field(default_factory=list)
    error: str | None = None

    @model_validator(mode="after")
    def validate_plan_sequence(self) -> "Task":
        # A plan task needs an explicit position; a standalone task has no plan
        # order. Requiring both fields together prevents ambiguous scheduling.
        if (self.plan_id is None) != (self.sequence_number is None):
            raise ValueError("plan_id and sequence_number must be supplied together")
        return self

    @property
    def has_issues(self) -> bool:
        return bool(
            self.mild_issues
            or self.moderate_issues
            or self.severe_issues
        )


def validate_task_list(tasks: list[dict[str, JsonValue]]) -> list[Task]:
    """Validate task records and their ordering within each plan."""
    parsed = [Task.model_validate(task) for task in tasks]
    positions: set[tuple[str, int]] = set()
    for task in parsed:
        if task.plan_id is None or task.sequence_number is None:
            continue
        position = (task.plan_id, task.sequence_number)
        # This requires the whole list: a single task cannot detect another task
        # occupying its position. Different plans may reuse the same number.
        if position in positions:
            raise ValueError(
                f"Duplicate sequence number {task.sequence_number} "
                f"in plan {task.plan_id!r}"
            )
        positions.add(position)
    return parsed


class CoordinatorDecision(Contract):
    """One proposed action; the parent graph validates it against task state."""

    # respond: send response to the teacher without changing a task.
    # create_task: create a queued task from task_type, title, and inputs.
    # dispatch: run an existing task's handler, optionally with new guidance.
    # complete_task: accept a result_ready task after required teacher approval.
    action: Literal[
        "respond",
        "create_task",
        "dispatch",
        "complete_task",
    ]

    # Required for dispatch and complete_task; generated by the parent on creation.
    task_id: str | None = None

    # Only create_task uses these fields. task_type and title are required;
    # inputs may be empty, and plan_id/sequence_number must appear together.
    task_type: str | None = None
    title: str | None = None
    plan_id: str | None = None
    sequence_number: int | None = Field(default=None, ge=1)
    inputs: dict[str, JsonValue] = Field(default_factory=dict)

    # Only dispatch uses guidance, for execution instructions or a rerun.
    guidance: str | None = None

    # Required for respond; other actions may also include a teacher-facing message.
    response: str | None = None


def validate_coordinator_decision(value: object) -> CoordinatorDecision:
    """Validate model output before the parent attempts to execute its action."""
    decision = CoordinatorDecision.model_validate(value)

    # Optional fields may be None, but supplied strings must contain text.
    for name in ("task_id", "task_type", "title", "plan_id", "guidance", "response"):
        text = getattr(decision, name)
        if text is not None and not text.strip():
            raise ValueError(f"{name} must not be blank")

    # Each action needs enough information to execute without guessing.
    if decision.action == "respond" and decision.response is None:
        raise ValueError("respond requires response")
    if decision.action == "create_task":
        if decision.task_type is None or decision.title is None:
            raise ValueError("create_task requires task_type and title")
        if (decision.plan_id is None) != (decision.sequence_number is None):
            raise ValueError("plan_id and sequence_number must be supplied together")
    if decision.action in ("dispatch", "complete_task") and decision.task_id is None:
        raise ValueError(f"{decision.action} requires task_id")

    # Reject fields belonging to another action instead of silently ignoring
    # them. Empty inputs and null optional fields are harmless defaults.
    if decision.action != "create_task":
        if any(item is not None for item in (
            decision.task_type, decision.title, decision.plan_id,
            decision.sequence_number,
        )) or decision.inputs:
            raise ValueError("Task creation fields are only allowed for create_task")
    if decision.action not in ("dispatch", "complete_task") and decision.task_id is not None:
        raise ValueError("task_id is only allowed for dispatch or complete_task")
    if decision.action != "dispatch" and decision.guidance is not None:
        raise ValueError("guidance is only allowed for dispatch")

    # Task existence, current status, registry membership, plan ordering,
    # and teacher approval require parent state, so the graph checks those.
    return decision


class DecisionValidationError(TypedDict):
    # Errors about this proposal, for the coordinator to correct.
    errors: list[str]

    # Corrections requested for this logical decision.
    # Preserve while revising; reset when starting a new decision.
    correction_attempts: int


class CoordinatorProposal(TypedDict, total=False):
    """Expected model-output fields; validation happens in the next node."""

    action: Literal[
        "respond",
        "create_task",
        "dispatch",
        "complete_task",
    ]
    task_id: str | None
    task_type: str | None
    title: str | None
    plan_id: str | None
    sequence_number: int | None
    inputs: dict[str, JsonValue]
    guidance: str | None
    response: str | None


class DecisionEnvelope(TypedDict):
    # Model-generated action fields, checked by the validation node.
    proposal: CoordinatorProposal

    # Application-managed validation errors; the model cannot reset the counter.
    validation_error: DecisionValidationError


class TeacherAssistantState(TypedDict):
    messages: Annotated[list[AnyMessage], add_messages]
    tasks: list[dict[str, JsonValue]]
    coordinator_decision: DecisionEnvelope | None
